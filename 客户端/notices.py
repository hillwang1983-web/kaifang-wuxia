TEXT_CODES = (0x64, 0x66, 0x69, 0x6A)      # 后面直接是 BIG5 文字
NO_MESSAGE = (0x06, 0x0D, 0x1E, 0x26, 0x2D)   # 分发表里有这几项，但块里没有任何文字


def decode_1a(payload: bytes, from_big5):
    """S2C 0x1A 载荷 -> 要显示的文字；这个子类型不是提示文字（或没有内容）返回 None。from_big5(bytes) -> str 由调用方给，免得这里依赖 jyclient。"""
    if not payload:
        return None
    sub = payload[0]
    if sub in TEXT_CODES:
        return from_big5(payload[1:]) or None
    hit = CODES.get(sub)
    if hit is None:
        return None
    text, append = hit
    return text + (from_big5(payload[1:]) if append else "")
